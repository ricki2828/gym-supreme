#!/usr/bin/env python3
"""Builds the Gym Supreme launcher icon (option A, barbell; Ricki 24-Nov).

Family with Run Supreme's "Track Bend": same white tile, zone ramp, 3.02 stroke,
1.56 gap and the bend's five lane heights. Five plates per side in the zone ramp
(largest blue inside, smallest red outside) on one ink bar drawn OVER the plates,
so the bar reads as one continuous axle (not an audio waveform).

Writes: assets/brand/svg/icon/*.svg, Android drawable/ic_launcher_{background,
foreground,monochrome}.xml, mipmap-anydpi-v26/ic_launcher.xml and the legacy
mipmap PNGs. With --preview DIR it also writes PNG previews incl. 48 dp crops.

    python3 tools/brand/build_icon.py [--preview DIR]
"""
import argparse
from pathlib import Path

from PIL import Image, ImageDraw

REPO = Path(__file__).resolve().parents[2]
RES = REPO / "android" / "app" / "src" / "main" / "res"
SVG = REPO / "assets" / "brand" / "svg" / "icon"

ZONES = ["#2F6DB5", "#2E9E5B", "#D9A21B", "#E86A1C", "#D6283B"]  # Run Supreme zone ramp (light)
INK = "#121417"
TILE = "#FFFFFF"
MONO = "#FFFFFF"
W, G = 3.02, 1.56                      # stripe and gap, as Run Supreme
H = [49.62, 40.46, 31.30, 22.14, 12.98]  # Run's lane heights, outer to inner
HANDLE_HALF = 5.0                      # half the bare handle between the inner plates
BAR = (24.7, 83.3)                     # bar ends, inside the 66 dp safe circle
BAR_H = 3.02


def plates():
    """(colour, x, y, w, h) per plate, both sides."""
    out = []
    for i in range(5):
        off = HANDLE_HALF + i * (W + G)
        h = H[i]
        for x in (54 + off, 54 - off - W):
            out.append((ZONES[i], x, 54 - h / 2, W, h))
    return out


def f(v):
    return f"{v:.2f}".rstrip("0").rstrip(".")


def pill_d(x, y, w, h):
    r = w / 2
    return (f"M{f(x)} {f(y + r)}A{f(r)} {f(r)} 0 0 1 {f(x + w)} {f(y + r)}"
            f"L{f(x + w)} {f(y + h - r)}A{f(r)} {f(r)} 0 0 1 {f(x)} {f(y + h - r)}Z")


def bar_d():
    x0, x1 = BAR
    y0, y1 = 54 - BAR_H / 2, 54 + BAR_H / 2
    return f"M{f(x0)} {f(y0)}L{f(x1)} {f(y0)}L{f(x1)} {f(y1)}L{f(x0)} {f(y1)}Z"


def layers(mono=False):
    ls = [(MONO if mono else c, pill_d(x, y, w, h)) for c, x, y, w, h in plates()]
    ls.append((MONO if mono else INK, bar_d()))  # bar last = on top, continuous
    return ls


def svg(ls, bg=None):
    body = (f'<rect width="108" height="108" fill="{bg}"/>' if bg else "")
    body += "".join(f'<path fill="{c}" d="{d}"/>' for c, d in ls)
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="108" height="108">{body}</svg>\n'


def vector(ls, bg=None):
    paths = ""
    if bg:
        paths += f'    <path\n        android:fillColor="{bg}"\n        android:pathData="M0 0H108V108H0Z" />\n'
    for c, d in ls:
        paths += f'    <path\n        android:fillColor="{c}"\n        android:pathData="{d}" />\n'
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            "<!-- Generated by tools/brand/build_icon.py. Do not edit by hand. -->\n"
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="108dp"\n    android:height="108dp"\n'
            '    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
            f"{paths}</vector>\n")


ADAPTIVE = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/brand/build_icon.py. Do not edit by hand. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
"""


def raster(px, mono=False, bg=TILE, mask="full", ss=4):
    """Rasterise the 72 dp visible area (18..90) of the 108 dp canvas to px x px."""
    n = px * ss
    s = n / 72.0
    im = Image.new("RGBA", (n, n), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    tile = Image.new("RGBA", (n, n), bg)
    im.alpha_composite(tile)
    def t(x, y):
        return ((x - 18) * s, (y - 18) * s)
    for c, x, y, w, h in plates():
        (x0, y0), (x1, y1) = t(x, y), t(x + w, y + h)
        d.rounded_rectangle([x0, y0, x1, y1], radius=(W / 2) * s, fill=MONO if mono else c)
    (x0, y0), (x1, y1) = t(BAR[0], 54 - BAR_H / 2), t(BAR[1], 54 + BAR_H / 2)
    d.rectangle([x0, y0, x1, y1], fill=MONO if mono else INK)
    if mask != "full":
        m = Image.new("L", (n, n), 0)
        md = ImageDraw.Draw(m)
        if mask == "circle":
            md.ellipse([0, 0, n - 1, n - 1], fill=255)
        else:  # squircle approximation
            md.rounded_rectangle([0, 0, n - 1, n - 1], radius=n * 0.28, fill=255)
        im.putalpha(m)
    return im.resize((px, px), Image.LANCZOS)


LEGACY = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--preview")
    a = ap.parse_args()
    SVG.mkdir(parents=True, exist_ok=True)
    (SVG / "ic_launcher_background.svg").write_text(svg([], bg=TILE))
    (SVG / "ic_launcher_foreground.svg").write_text(svg(layers()))
    (SVG / "ic_launcher_monochrome.svg").write_text(svg(layers(mono=True)))
    (SVG / "ic_launcher_full.svg").write_text(svg(layers(), bg=TILE))
    (RES / "drawable").mkdir(exist_ok=True)
    (RES / "drawable" / "ic_launcher_background.xml").write_text(vector([], bg=TILE))
    (RES / "drawable" / "ic_launcher_foreground.xml").write_text(vector(layers()))
    (RES / "drawable" / "ic_launcher_monochrome.xml").write_text(vector(layers(mono=True)))
    (RES / "mipmap-anydpi-v26").mkdir(exist_ok=True)
    (RES / "mipmap-anydpi-v26" / "ic_launcher.xml").write_text(ADAPTIVE)
    for dpi, px in LEGACY.items():
        raster(px, mask="circle").save(RES / f"mipmap-{dpi}" / "ic_launcher.png")
    if a.preview:
        p = Path(a.preview)
        p.mkdir(parents=True, exist_ok=True)
        sheet = Image.new("RGBA", (1100, 560), "#E9E7E2")
        x = 30
        for mask in ("circle", "squircle"):
            sheet.alpha_composite(raster(200, mask=mask), (x, 30)); x += 230
        sheet.alpha_composite(raster(200, mono=True, bg="#22303F", mask="circle"), (x, 30)); x += 230
        # 48 dp at mdpi (48 px), xxhdpi (144 px) and the 48 px crop shown at 4x nearest-neighbour
        sheet.alpha_composite(raster(48, mask="circle"), (x, 30))
        sheet.alpha_composite(raster(48, mono=True, bg="#22303F", mask="circle"), (x + 70, 30))
        sheet.alpha_composite(raster(144, mask="circle"), (30, 300))
        sheet.alpha_composite(raster(144, mono=True, bg="#22303F", mask="circle"), (200, 300))
        sheet.alpha_composite(raster(48, mask="circle").resize((192, 192), Image.NEAREST), (380, 300))
        sheet.alpha_composite(raster(48, mono=True, bg="#22303F", mask="circle").resize((192, 192), Image.NEAREST), (600, 300))
        sheet.save(p / "gym-icon-A-preview.png")
        raster(48, mask="circle").save(p / "gym-icon-A-48px.png")


if __name__ == "__main__":
    main()
